"""
custom_vla_eval.py
==================

Stage 2 of the classroom LIBERO + SmolVLA workflow.

Input:
    A JSON task file generated by libero_custom_task_builder.py

Example:
    ~/lerobot/custom_libero_tasks/scene_A/put_the_black_bowl_on_the_stove.json

What this script does:
    1. Read the custom task JSON and BDDL.
    2. Reuse the original LIBERO scene and fixed initial state.
    3. Replace the official BDDL with the student's custom BDDL.
    4. Feed camera images + robot state + custom language instruction to SmolVLA.
    5. Execute actions in closed loop.
    6. Save an MP4 rollout for each episode.
    7. Report SUCCESS / FAILURE and success rate.

This script does NOT train or finetune SmolVLA.
"""

