def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Run SmolVLA on a custom LIBERO task generated "
            "by libero_custom_task_builder.py"
        )
    )

    parser.add_argument(
        "--task",
        type=str,
        default=None,
        help=(
            "Path to generated task JSON. "
            "If omitted, an interactive menu is shown."
        ),
    )

    parser.add_argument(
        "--model",
        type=str,
        default=DEFAULT_MODEL,
        help="LeRobot / Hugging Face policy path.",
    )

    parser.add_argument(
        "--episodes",
        type=int,
        default=1,
        help="Number of rollout episodes.",
    )

    parser.add_argument(
        "--device",
        type=str,
        default="auto",
        help="auto, cuda, cuda:0, or cpu",
    )

    parser.add_argument(
        "--empty-cameras",
        type=int,
        default=DEFAULT_EMPTY_CAMERAS,
        help=(
            "SmolVLA empty camera count. "
            "The course LIBERO setup previously used 1."
        ),
    )

    parser.add_argument(
        "--max-steps",
        type=int,
        default=None,
        help=(
            "Override episode horizon. "
            "Default is chosen from the base LIBERO suite."
        ),
    )

    parser.add_argument(
        "--seed",
        type=int,
        default=0,
        help="Seed of the first episode.",
    )

    parser.add_argument(
        "--vary-init-state",
        action="store_true",
        help=(
            "Use different official init states across resets. "
            "Default keeps the exact same fixed scene."
        ),
    )

    parser.add_argument(
        "--init-state-index",
        type=int,
        default=DEFAULT_INIT_STATE_INDEX,
        help="Official init-state index used for the fixed scene.",
    )

    parser.add_argument(
        "--video-fps",
        type=int,
        default=DEFAULT_FPS,
    )

    return parser.parse_args()


def main():
    args = parse_args()

    if args.episodes <= 0:
        raise ValueError("--episodes must be >= 1")

    if args.empty_cameras < 0:
        raise ValueError("--empty-cameras must be >= 0")

    # --------------------------------------------------------------
    # 1. Select task
    # --------------------------------------------------------------

    if args.task is None:
        task_json_path = interactive_choose_task()
    else:
        task_json_path = Path(
            args.task
        ).expanduser().resolve()

    if not task_json_path.exists():
        raise FileNotFoundError(
            task_json_path
        )

    metadata = json.loads(
        task_json_path.read_text(
            encoding="utf-8"
        )
    )

    instruction = metadata[
        "instruction"
    ]

    bddl_path = Path(
        metadata["bddl_file"]
    ).expanduser()

    if not bddl_path.is_absolute():
        bddl_path = (
            task_json_path.parent
            / bddl_path
        ).resolve()

    if not bddl_path.exists():
        raise FileNotFoundError(
            f"Custom BDDL not found:\n{bddl_path}"
        )

    base_suite = metadata[
        "base_suite"
    ]

    max_steps = (
        args.max_steps
        if args.max_steps is not None
        else DEFAULT_MAX_STEPS.get(
            base_suite,
            500,
        )
    )

    device = choose_device(
        args.device
    )

    # --------------------------------------------------------------
    # 2. Print run configuration
    # --------------------------------------------------------------

    print(
        "\n"
        + "=" * 78
    )

    print(
        "CUSTOM SmolVLA + LIBERO EVALUATION"
    )

    print(
        "=" * 78
    )

    print(
        f"\nScene             : {metadata.get('scene')}"
    )

    print(
        f"Base suite        : {base_suite}"
    )

    print(
        f"Base task ID      : {metadata['base_task_id']}"
    )

    print(
        f"Instruction       : {instruction}"
    )

    print(
        f"Custom BDDL       : {bddl_path}"
    )

    print(
        f"Model             : {args.model}"
    )

    print(
        f"Device            : {device}"
    )

    print(
        f"Episodes          : {args.episodes}"
    )

    print(
        f"Max steps         : {max_steps}"
    )

    print(
        f"Observation size  : {DEFAULT_OBS_SIZE}x{DEFAULT_OBS_SIZE}"
    )

    print(
        f"Fixed init state  : {not args.vary_init_state}"
    )

    print(
        f"Init state index  : {args.init_state_index}"
    )

    # --------------------------------------------------------------
    # 3. Load SmolVLA
    # --------------------------------------------------------------

    policy_cfg = load_policy_config(
        model_id=args.model,
        device=device,
        empty_cameras=args.empty_cameras,
    )

    camera_mapping = infer_camera_mapping(
        policy_cfg
    )

    print(
        "\nCamera mapping:"
    )

    print(
        json.dumps(
            camera_mapping,
            indent=2,
        )
    )

    policy, preprocessor, postprocessor = (
        load_policy_and_processors(
            model_id=args.model,
            policy_cfg=policy_cfg,
            device=device,
        )
    )

    env_preprocessor, env_postprocessor = (
        make_env_processors(
            policy_cfg=policy_cfg,
            base_suite=base_suite,
            camera_mapping=camera_mapping,
        )
    )

    # --------------------------------------------------------------
    # 4. Create custom environment
    # --------------------------------------------------------------

    env = make_vector_env(
        metadata=metadata,
        bddl_path=bddl_path,
        instruction=instruction,
        camera_mapping=camera_mapping,
        max_steps=max_steps,
        fixed_init_state=not args.vary_init_state,
        init_state_index=args.init_state_index,
    )

    # --------------------------------------------------------------
    # 5. Prepare output
    # --------------------------------------------------------------

    task_slug = slugify(
        instruction
    )

    output_dir = (
        OUTPUT_ROOT
        / f"scene_{metadata.get('scene', 'custom')}"
        / task_slug
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    results = []

    # --------------------------------------------------------------
    # 6. Rollouts
    # --------------------------------------------------------------

    try:
        for episode_index in range(
            args.episodes
        ):
            video_path = (
                output_dir
                / f"episode_{episode_index:02d}.mp4"
            )

            result = run_episode(
                env=env,
                policy=policy,
                env_preprocessor=env_preprocessor,
                env_postprocessor=env_postprocessor,
                preprocessor=preprocessor,
                postprocessor=postprocessor,
                instruction=instruction,
                device=device,
                max_steps=max_steps,
                seed=args.seed + episode_index,
                video_path=video_path,
                video_fps=args.video_fps,
            )

            result[
                "episode"
            ] = episode_index

            results.append(
                result
            )

    finally:
        env.close()

    # --------------------------------------------------------------
    # 7. Save summary
    # --------------------------------------------------------------

    n_success = sum(
        1
        for item in results
        if item["success"]
    )

    success_rate = (
        n_success
        / len(results)
        if results
        else 0.0
    )

    summary = {
        "scene": metadata.get(
            "scene"
        ),
        "instruction": instruction,
        "custom_bddl": str(
            bddl_path
        ),
        "model": args.model,
        "device": str(
            device
        ),
        "episodes": len(
            results
        ),
        "n_success": n_success,
        "success_rate": success_rate,
        "fixed_init_state": (
            not args.vary_init_state
        ),
        "init_state_index": (
            args.init_state_index
        ),
        "results": results,
    }

    result_path = (
        output_dir
        / "results.json"
    )

    result_path.write_text(
        json.dumps(
            summary,
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )

    # --------------------------------------------------------------
    # 8. Human-readable result
    # --------------------------------------------------------------

    print(
        "\n"
        + "=" * 78
    )

    print(
        "EVALUATION COMPLETE"
    )

    print(
        "=" * 78
    )

    for item in results:
        print(
            f"Episode {item['episode']:02d}: "
            f"{'SUCCESS' if item['success'] else 'FAILURE'} "
            f"| steps={item['steps']}"
        )

    print(
        f"\nSuccess rate: "
        f"{n_success}/{len(results)} "
        f"= {success_rate * 100:.1f}%"
    )

    print(
        f"\nOutput directory:\n{output_dir}"
    )

    print(
        f"\nResults JSON:\n{result_path}"
    )


if __name__ == "__main__":
    main()
