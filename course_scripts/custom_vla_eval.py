def discover_task_jsons(root: Path) -> list[Path]:
    if not root.exists():
        return []

    paths = []

    for path in sorted(root.rglob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))

            required = {
                "scene",
                "base_suite",
                "base_task_id",
                "instruction",
                "bddl_file",
            }

            if required.issubset(data):
                paths.append(path)

        except Exception:
            continue

    return paths


def interactive_choose_task() -> Path:
    tasks = discover_task_jsons(TASK_ROOT)

    if not tasks:
        raise FileNotFoundError(
            f"No generated custom task JSON files found under:\n{TASK_ROOT}\n\n"
            "Run libero_custom_task_builder.py first."
        )

    print("\n" + "=" * 78)
    print("AVAILABLE CUSTOM TASKS")
    print("=" * 78)

    for i, path in enumerate(tasks, start=1):
        data = json.loads(path.read_text(encoding="utf-8"))

        print(
            f"\n[{i}] Scene {data['scene']} | "
            f"{data['instruction']}"
        )

        print(f"    {path}")

    while True:
        value = input("\nChoose task number: ").strip()

        try:
            index = int(value) - 1

            if 0 <= index < len(tasks):
                return tasks[index]

        except ValueError:
            pass

        print("Invalid selection.")


