def reset_pipeline(obj):
    if hasattr(obj, "reset"):
        try:
            obj.reset()
        except TypeError:
            pass


def run_episode(
    *,
    env,
    policy,
    env_preprocessor,
    env_postprocessor,
    preprocessor,
    postprocessor,
    instruction: str,
    device: torch.device,
    max_steps: int,
    seed: int,
    video_path: Path,
    video_fps: int,
):
    policy.reset()
    reset_pipeline(env_preprocessor)
    reset_pipeline(env_postprocessor)
    reset_pipeline(preprocessor)
    reset_pipeline(postprocessor)

    # Match official lerobot-eval behavior for relative-action policies.
    # SmolVLA may output an action chunk. All queued actions in that chunk
    # must stay anchored to the robot state at the moment the chunk was
    # predicted; otherwise each following tick can incorrectly re-anchor
    # the remaining relative actions to a newer robot state.
    
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)

    if device.type == "cuda":
        torch.cuda.manual_seed_all(seed)

    observation, _ = env.reset(seed=seed)

    frames = []

    # Initial frame.
    try:
        frame = env.envs[0].render()
        frames.append(np.asarray(frame, dtype=np.uint8))
    except Exception as exc:
        print(f"[Video] Could not capture initial render frame: {exc}")

    success = False
    executed_steps = 0

    print(
        f"\nRunning episode | seed={seed} | max_steps={max_steps}"
    )

    for step in range(max_steps):
        # --------------------------------------------------------------
        # Official LeRobot rollout ordering:
        # raw Gym observation
        # -> preprocess_observation
        # -> add language task
        # -> LIBERO environment processor
        # -> SmolVLA policy processor
        # -> policy.select_action
        # -> postprocessor
        # -> env.step
        # --------------------------------------------------------------

        batch = preprocess_observation(observation)

        # Batch size = 1.
        batch["task"] = [instruction]

        batch = env_preprocessor(batch)
        batch = preprocessor(batch)

        # Extra compatibility guarantee:
        # keep every tensor on the same device as the model.
        batch = move_to_device(batch, device)

        use_amp = bool(
            getattr(policy.config, "use_amp", False)
        )

        if (
            device.type == "cuda"
            and use_amp
        ):
            amp_context = torch.autocast(
                device_type="cuda"
            )
        else:
            amp_context = nullcontext()

        with torch.inference_mode(), amp_context:
            action = policy.select_action(batch)

        action = postprocessor(action)

        # Environment postprocessor is currently identity for LIBERO,
        # but use it anyway to stay aligned with official lerobot-eval.
        transition = {
            "action": action
        }

        transition = env_postprocessor(
            transition
        )

        action = transition["action"]

        if isinstance(action, torch.Tensor):
            action_np = action.detach().to("cpu").numpy()
        else:
            action_np = np.asarray(action)

        if action_np.ndim == 1:
            action_np = action_np[None, :]

        observation, reward, terminated, truncated, info = env.step(
            action_np
        )

        executed_steps = step + 1

        # Capture frame after the action.
        try:
            frame = env.envs[0].render()
            frames.append(
                np.asarray(
                    frame,
                    dtype=np.uint8,
                )
            )
        except Exception as exc:
            if step == 0:
                print(f"[Video] Render warning: {exc}")

        # Prefer the underlying LIBERO success detector.
        try:
            inner_env = env.envs[0]._env

            if inner_env is not None:
                success = bool(
                    inner_env.check_success()
                )

        except Exception:
            success = get_nested_info_success(
                info
            )

        if step % 25 == 0 or success:
            print(
                f"  step {step:03d} | "
                f"success={success}"
            )

        if success:
            break

        term = bool(
            np.asarray(
                terminated
            ).reshape(-1)[0]
        )

        trunc = bool(
            np.asarray(
                truncated
            ).reshape(-1)[0]
        )

        if term or trunc:
            success = (
                success
                or get_nested_info_success(
                    info
                )
            )
            break

    print(
        f"Episode finished | "
        f"steps={executed_steps} | "
        f"{'SUCCESS' if success else 'FAILURE'}"
    )

    print(
        f"Saving video: {video_path}"
    )

    write_mp4(
        frames,
        video_path,
        fps=video_fps,
    )

    return {
        "success": bool(success),
        "steps": int(executed_steps),
        "seed": int(seed),
        "video": str(video_path),
    }


