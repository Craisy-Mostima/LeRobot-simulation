class CustomTaskLiberoEnv(LeRobotLiberoEnv):
    """
    Reuse LeRobot's official LIBERO wrapper, but replace:
      - official BDDL path -> custom student BDDL
      - official language -> custom student instruction

    We keep the original task's init-state data because Stage 1 copies
    the original scene and changes only language / goal / obj_of_interest.
    """

    def __init__(
        self,
        *,
        base_suite_name: str,
        base_task_id: int,
        custom_bddl: Path,
        instruction: str,
        camera_mapping: dict[str, str],
        max_steps: int,
        fixed_init_state: bool,
        init_state_index: int,
    ):
        suite_cls = benchmark.get_benchmark_dict().get(base_suite_name)

        if suite_cls is None:
            raise ValueError(
                f"Unknown LIBERO suite: {base_suite_name}"
            )

        suite = suite_cls()

        candidate_kwargs = {
            "task_suite": suite,
            "task_id": int(base_task_id),
            "task_suite_name": base_suite_name,
            "episode_length": int(max_steps),
            "camera_name": [
                "agentview_image",
                "robot0_eye_in_hand_image",
            ],
            "obs_type": "pixels_agent_pos",
            "render_mode": "rgb_array",
            "observation_width": DEFAULT_OBS_SIZE,
            "observation_height": DEFAULT_OBS_SIZE,
            "visualization_width": 640,
            "visualization_height": 480,
            "init_states": True,
            "episode_index": int(init_state_index),
            "n_envs": 1,
            "camera_name_mapping": camera_mapping,
            "num_steps_wait": 10,
            "control_freq": DEFAULT_FPS,
            "control_mode": "relative",
            "hard_reset": True,
        }

        # Filter kwargs for compatibility with nearby LeRobot versions.
        parameters = inspect.signature(
            LeRobotLiberoEnv.__init__
        ).parameters

        kwargs = {
            key: value
            for key, value in candidate_kwargs.items()
            if key in parameters
        }

        super().__init__(**kwargs)

        # _ensure_env() is deferred until reset() in current LeRobot.
        # Replace these before the first reset.
        self._task_bddl_file = str(custom_bddl)
        self.task_description = instruction
        self.task = slugify(instruction)

        self._custom_instruction = instruction
        self._fixed_init_state = fixed_init_state
        self._fixed_init_index = int(init_state_index)

        # Keep max horizon explicit even if an older wrapper ignores
        # episode_length in the constructor.
        if hasattr(self, "_max_episode_steps"):
            self._max_episode_steps = int(max_steps)

    def reset(self, seed=None, **kwargs):
        # If the course wants the exact same visible scene every rollout,
        # force the same official init-state index before each reset.
        if self._fixed_init_state and hasattr(self, "init_state_id"):
            self.init_state_id = self._fixed_init_index

        return super().reset(seed=seed, **kwargs)


def make_vector_env(
    *,
    metadata: dict,
    bddl_path: Path,
    instruction: str,
    camera_mapping: dict[str, str],
    max_steps: int,
    fixed_init_state: bool,
    init_state_index: int,
):
    def make_one():
        return CustomTaskLiberoEnv(
            base_suite_name=metadata["base_suite"],
            base_task_id=int(metadata["base_task_id"]),
            custom_bddl=bddl_path,
            instruction=instruction,
            camera_mapping=camera_mapping,
            max_steps=max_steps,
            fixed_init_state=fixed_init_state,
            init_state_index=init_state_index,
        )

    # The official eval pipeline is vectorized. Using a one-env SyncVectorEnv
    # also ensures nested LIBERO state tensors carry a batch dimension.
    try:
        return gym.vector.SyncVectorEnv(
            [make_one],
            autoreset_mode=gym.vector.AutoresetMode.NEXT_STEP,
        )

    except Exception:
        # Compatibility with older Gymnasium versions.
        return gym.vector.SyncVectorEnv(
            [make_one]
        )


