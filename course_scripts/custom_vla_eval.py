def load_policy_config(
    model_id: str,
    device: torch.device,
    empty_cameras: int,
):
    print("\nLoading policy configuration...")

    cfg = PreTrainedConfig.from_pretrained(model_id)

    # Important for make_policy / processor behavior.
    if hasattr(cfg, "pretrained_path"):
        cfg.pretrained_path = model_id

    if hasattr(cfg, "device"):
        cfg.device = str(device)

    if hasattr(cfg, "empty_cameras"):
        cfg.empty_cameras = empty_cameras

    return cfg


def infer_camera_mapping(policy_cfg) -> dict[str, str]:
    """
    Map LIBERO's two raw cameras to the image feature names expected by
    the checkpoint.

    Your existing setup used camera1/camera2. Newer LeRobot checkpoints
    may use image/image2. We inspect input_features and choose dynamically.
    """
    input_features = getattr(policy_cfg, "input_features", {}) or {}

    image_keys = [
        key
        for key in input_features
        if "observation.images." in key
        and "empty_camera" not in key
    ]

    image_names = [
        key.split("observation.images.", 1)[1]
        for key in image_keys
    ]

    # Preserve familiar/common pairs first.
    preferred_pairs = [
        ("camera1", "camera2"),
        ("image", "image2"),
    ]

    names_set = set(image_names)

    for first, second in preferred_pairs:
        if first in names_set and second in names_set:
            return {
                "agentview_image": first,
                "robot0_eye_in_hand_image": second,
            }

    if len(image_names) >= 2:
        return {
            "agentview_image": image_names[0],
            "robot0_eye_in_hand_image": image_names[1],
        }

    # The checkpoint/version you previously evaluated used camera1/camera2,
    # so this is the safest fallback for your current course environment.
    return {
        "agentview_image": "camera1",
        "robot0_eye_in_hand_image": "camera2",
    }


def load_policy_and_processors(
    model_id: str,
    policy_cfg,
    device: torch.device,
):
    print(f"\nLoading SmolVLA weights: {model_id}")
    print("This may use the local Hugging Face cache if already downloaded.")

    policy_class = get_policy_class(policy_cfg.type)

    policy = policy_class.from_pretrained(
        model_id,
        config=policy_cfg,
    )

    policy = policy.to(device)
    policy.eval()

    # Official LeRobot eval overrides the device processor so inference
    # tensors follow the model device. Older versions may not recognize
    # this override, so we fall back cleanly.
    try:
        preprocessor, postprocessor = make_pre_post_processors(
            policy_cfg=policy_cfg,
            pretrained_path=model_id,
            preprocessor_overrides={
                "device_processor": {
                    "device": str(device)
                }
            },
        )

    except Exception as exc:
        print(
            "\n[Compatibility] Device processor override was not accepted."
        )
        print(f"[Compatibility] Retrying without override: {exc}")

        preprocessor, postprocessor = make_pre_post_processors(
            policy_cfg=policy_cfg,
            pretrained_path=model_id,
        )

    return policy, preprocessor, postprocessor


def make_env_processors(policy_cfg, base_suite: str, camera_mapping: dict[str, str]):
    """
    Build the official LeRobot LIBERO processor:
    - 180° camera orientation correction
    - LIBERO quaternion -> axis-angle
    - 8D state: eef_pos(3) + axis-angle(3) + gripper_qpos(2)
    """
    if LiberoEnvConfig is not None:
        try:
            env_cfg = LiberoEnvConfig(
                task=base_suite,
                task_ids=[0],
                obs_type="pixels_agent_pos",
                camera_name_mapping=camera_mapping,
                observation_height=DEFAULT_OBS_SIZE,
                observation_width=DEFAULT_OBS_SIZE,
                control_mode="relative",
            )

            return make_env_pre_post_processors(
                env_cfg=env_cfg,
                policy_cfg=policy_cfg,
            )

        except Exception as exc:
            print(
                "\n[Compatibility] Could not construct env processors "
                "through LiberoEnvConfig."
            )
            print(f"[Compatibility] {exc}")

    # Fallback for nearby LeRobot versions.
    try:
        from lerobot.processor import LiberoProcessorStep, PolicyProcessorPipeline

        return (
            PolicyProcessorPipeline(
                steps=[LiberoProcessorStep()]
            ),
            PolicyProcessorPipeline(
                steps=[]
            ),
        )

    except Exception as exc:
        raise RuntimeError(
            "Could not build the official LIBERO observation processor.\n"
            "Your LeRobot version may differ substantially from the version "
            "used by this script."
        ) from exc


