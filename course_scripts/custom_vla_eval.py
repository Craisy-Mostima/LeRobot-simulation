def slugify(text: str, max_len: int = 90) -> str:
    text = text.lower().replace("-", " ")
    text = re.sub(r"[^a-z0-9\s]", "", text)
    text = re.sub(r"\s+", "_", text).strip("_")
    return (text or "custom_task")[:max_len].rstrip("_")


def move_to_device(value: Any, device: torch.device) -> Any:
    """Recursively move tensors to the policy device."""
    if isinstance(value, torch.Tensor):
        return value.to(device, non_blocking=(device.type == "cuda"))
    if isinstance(value, dict):
        return {k: move_to_device(v, device) for k, v in value.items()}
    if isinstance(value, list):
        return [move_to_device(v, device) for v in value]
    if isinstance(value, tuple):
        return tuple(move_to_device(v, device) for v in value)
    return value


def choose_device(requested: str) -> torch.device:
    if requested != "auto":
        return torch.device(requested)

    if torch.cuda.is_available():
        return torch.device("cuda")

    if hasattr(torch.backends, "mps") and torch.backends.mps.is_available():
        return torch.device("mps")

    return torch.device("cpu")


def write_mp4(frames: list[np.ndarray], path: Path, fps: int) -> None:
    """
    Save RGB uint8 frames to MP4.
    Try imageio first; fall back to OpenCV.
    """
    if not frames:
        raise RuntimeError("No video frames were captured.")

    path.parent.mkdir(parents=True, exist_ok=True)

    frames = [
        np.asarray(frame, dtype=np.uint8)
        for frame in frames
    ]

    # First choice: imageio / imageio-ffmpeg
    try:
        import imageio.v2 as imageio

        imageio.mimwrite(
            path,
            frames,
            fps=fps,
            codec="libx264",
            quality=8,
        )
        return

    except Exception as imageio_error:
        print("\n[Video] imageio writer failed:")
        print(imageio_error)
        print("[Video] Trying OpenCV fallback...")

    # Fallback: OpenCV
    try:
        import cv2

        height, width = frames[0].shape[:2]

        writer = cv2.VideoWriter(
            str(path),
            cv2.VideoWriter_fourcc(*"mp4v"),
            fps,
            (width, height),
        )

        if not writer.isOpened():
            raise RuntimeError("cv2.VideoWriter could not open the MP4 file.")

        for frame in frames:
            if frame.shape[:2] != (height, width):
                frame = cv2.resize(frame, (width, height))

            # RGB -> BGR
            writer.write(frame[:, :, ::-1])

        writer.release()
        return

    except Exception as cv_error:
        raise RuntimeError(
            "Could not save MP4.\n"
            "Install one of these inside the lerobot environment:\n"
            "  pip install imageio imageio-ffmpeg\n"
            "or make sure opencv-python is installed.\n"
            f"OpenCV error: {cv_error}"
        ) from cv_error


def get_nested_info_success(info: Any) -> bool:
    """
    Gym VectorEnv packs infos differently across Gymnasium versions.
    This helper extracts is_success when possible.
    """
    if isinstance(info, dict):
        if "is_success" in info:
            value = info["is_success"]

            if isinstance(value, np.ndarray):
                return bool(value.reshape(-1)[0])

            if isinstance(value, (list, tuple)):
                return bool(value[0])

            return bool(value)

        # Some versions put final infos in nested structures.
        for key in ("final_info", "final_infos"):
            if key in info:
                nested = info[key]

                if isinstance(nested, np.ndarray):
                    nested = nested.reshape(-1)[0]

                if isinstance(nested, (list, tuple)) and nested:
                    nested = nested[0]

                if isinstance(nested, dict):
                    return get_nested_info_success(nested)

    return False


